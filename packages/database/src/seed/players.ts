const V = (
  id: string,
  playerId: string,
  label: string,
  season: string,
  clubId: string,
  position: Position,
  altPositions: Position[],
  rating: number,
  stats: FaceStats,
  shirtNumber: number,
  milestone?: string,
  nationCode?: string,
): PlayerVersion => {
  const player = PLAYERS.find((p) => p.id === playerId);
  if (!player) throw new Error(`Seed: jugador ${playerId} inexistente`);
  return {
    id,
    playerId,
    label,
    season,
    clubId,
    nationCode: nationCode ?? player.nationCode,
    position,
    altPositions,
    rating,
    stats,
    year: seasonToYear(season),
    shirtNumber,
    milestone,
  };
};

